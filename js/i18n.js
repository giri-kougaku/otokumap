(function () {
  var KEY = 'otoku_lang';
  var dict = window.STRINGS;

  function detect() {
    try {
      var saved = localStorage.getItem(KEY);
      if (saved && dict[saved]) return saved;
    } catch (e) { /* storage blocked */ }
    var nav = (navigator.language || 'en').toLowerCase();
    return nav.indexOf('ja') === 0 ? 'ja' : 'en';
  }

  var I18N = {
    lang: detect(),
    t: function (key, vars) {
      var pack = dict[this.lang] || dict.en;
      var s = pack[key];
      if (s === undefined) s = dict.en[key];
      if (s === undefined) s = key;
      if (vars) {
        Object.keys(vars).forEach(function (k) {
          s = s.split('{' + k + '}').join(String(vars[k]));
        });
      }
      return s;
    },
    setLang: function (l) {
      if (!dict[l] || l === this.lang) {
        if (dict[l]) this.applyStatic();
        return;
      }
      this.lang = l;
      try { localStorage.setItem(KEY, l); } catch (e) { /* ignore */ }
      document.documentElement.lang = l === 'ja' ? 'ja' : 'en';
      this.applyStatic();
      window.dispatchEvent(new CustomEvent('langchange', { detail: { lang: l } }));
    },
    toggle: function () {
      this.setLang(this.lang === 'ja' ? 'en' : 'ja');
    },
    applyStatic: function (root) {
      root = root || document;
      root.querySelectorAll('[data-i18n]').forEach(function (el) {
        el.textContent = I18N.t(el.getAttribute('data-i18n'));
      });
      root.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
        el.setAttribute('placeholder', I18N.t(el.getAttribute('data-i18n-placeholder')));
      });
      root.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
        el.setAttribute('aria-label', I18N.t(el.getAttribute('data-i18n-aria')));
      });
      root.querySelectorAll('[data-i18n-title]').forEach(function (el) {
        el.setAttribute('title', I18N.t(el.getAttribute('data-i18n-title')));
      });
      document.documentElement.lang = I18N.lang === 'ja' ? 'ja' : 'en';
    }
  };

  window.I18N = I18N;
  window.t = function (key, vars) { return I18N.t(key, vars); };
  document.documentElement.lang = I18N.lang === 'ja' ? 'ja' : 'en';
  document.addEventListener('DOMContentLoaded', function () { I18N.applyStatic(); });
})();
